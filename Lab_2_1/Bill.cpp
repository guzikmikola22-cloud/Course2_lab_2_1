#include "Bill.h"
#include <sstream>

// ================= КОНСТРУКТОРИ =================

// Конструктор за умовчанням (без аргументів).
// Викликається автоматично, коли ми створюємо об'єкт без передачі значень: Bill b;
Bill::Bill() {
    setFirst(0);    // Використовуємо сетер для безпечної ініціалізації тривалості нулем
    setSecond(0.0); // Використовуємо сетер для ініціалізації вартості нулем
}

// Конструктор ініціалізації (з параметрами).
// Викликається, коли ми передаємо значення при створенні: Bill b(10, 2.5);
Bill::Bill(unsigned int duration, double price) {
    setFirst(duration); // Встановлюємо задану тривалість розмови
    setSecond(price);   // Встановлюємо задану вартість хвилини
}

// Конструктор копіювання.
// Потрібен для того, щоб створити новий об'єкт як точну копію існуючого: Bill b2 = b1;
Bill::Bill(const Bill& other) {
    first = other.first;   // Копіюємо поле first
    second = other.second; // Копіюємо поле second
}

// ================= ДЕСТРУКТОР =================

// Деструктор викликається автоматично при знищенні об'єкта (наприклад, при виході з функції).
// В даному випадку він порожній, оскільки ми не використовуємо динамічну пам'ять.
Bill::~Bill() {}

// ================= МЕТОДИ ДОСТУПУ (ГЕТЕРИ ТА СЕТЕРИ) =================

// Гетер для поля first. Повертає тривалість розмови. 
// const гарантує, що метод не змінить сам об'єкт.
unsigned int Bill::getFirst() const { return first; }

// Сетер для поля first. Дозволяє безпечно змінити тривалість розмови.
void Bill::setFirst(unsigned int duration) {
    first = duration;
}

// Гетер для поля second. Повертає вартість однієї хвилини.
double Bill::getSecond() const { return second; }

// Сетер для поля second. 
// Тут реалізована перевірка: якщо намагаються встановити від'ємну ціну, встановлюємо 0.0.
void Bill::setSecond(double price) {
    if (price >= 0) {
        second = price;
    }
    else {
        second = 0.0;
    }
}

// ================= БІЗНЕС-ЛОГІКА =================

// Метод обчислення загальної вартості розмови
// Повертає добуток тривалості на вартість однієї хвилини.
double Bill::cost() const {
    return first * second;
}

// ================= ПЕРЕВАНТАЖЕННЯ ОПЕРАЦІЙ =================

// Перевантаження операції присвоєння (b1 = b2).
Bill& Bill::operator=(const Bill& other) {
    // Перевірка на самоприсвоєння 
    if (this != &other) {
        first = other.first;   // Копіюємо тривалість
        second = other.second; // Копіюємо вартість
    }
    return *this; // Повертаємо сам об'єкт для ланцюгового присвоєння (a = b = c)
}

// Перетворення об'єкта в рядок (string).
// Зручно для виводу інформації на екран або в файл.
Bill::operator string() const {
    stringstream ss; // Використовуємо stringstream для формування рядка
    ss << "Тривалість (first): " << first << " хв, Вартість хв (second): " << second << " грн";
    return ss.str(); // Повертаємо сформований рядок
}

// --- Перевантаження інкременту (++) та декременту (--) ---

// Префіксний інкремент (++b). 
// За умовою завдання, він має модифікувати поле first (тривалість).
Bill& Bill::operator++() {
    ++first;      // Збільшуємо тривалість на 1
    return *this; // Повертаємо змінений об'єкт
}

// Префіксний декремент (--b). 
// За умовою, модифікує поле first.
Bill& Bill::operator--() {
    if (first > 0) { // Перевірка, щоб тривалість не стала від'ємною (бо unsigned int)
        --first;
    }
    return *this; // Повертаємо змінений об'єкт
}

// Постфіксний інкремент (b++). 
// За умовою, має модифікувати поле second (вартість).
Bill Bill::operator++(int) {
    Bill temp(*this); // Зберігаємо стан об'єкта ДО зміни
    ++second;         // Збільшуємо вартість на 1
    return temp;      // Повертаємо СТАРЕ значення (таке правило постфіксної операції)
}

// Постфіксний декремент (b--). 
// За умовою, модифікує поле second.
Bill Bill::operator--(int) {
    Bill temp(*this);     // Зберігаємо стан об'єкта ДО зміни
    if (second >= 1.0) {  // Перевірка, щоб ціна не стала від'ємною
        --second;
    }
    else {
        second = 0.0;
    }
    return temp;          // Повертаємо СТАРЕ значення
}

// ================= ДРУЖНІ ФУНКЦІЇ ВВОДУ/ВИВОДУ =================

// Перевантаження оператора виводу (<<) для роботи з потоком (наприклад, cout).
ostream& operator<<(ostream& out, const Bill& b) {
    // Використовуємо вже написаний нами метод перетворення в рядок
    out << string(b);
    return out; // Повертаємо потік, щоб можна було писати cout << b1 << b2;
}

// Перевантаження оператора вводу (>>) для роботи з клавіатурою (cin).
istream& operator>>(istream& in, Bill& b) {
    unsigned int duration;
    double price;

    cout << " Введіть тривалість (хв): ";
    in >> duration;

    cout << " Введіть вартість 1 хв (грн): ";
    in >> price;

    // Встановлюємо отримані значення через сетери для безпеки
    b.setFirst(duration);
    b.setSecond(price);

    return in; // Повертаємо потік
}